"""Shared paths, constants and small helpers for the poster-motion pipeline.

A project is one folder. Every script takes it as its first argument and
reads/writes only inside it:

    <project>/
      posters/            input stills (p1.png, p2.png ...), any size
      assets/layers/<id>/ ink.png object.png plate.png poster.png + accents
      assets/music/       bed.m4a, beats.json
      assets/fonts/       woff2 files fetched by build_composition.py
      layers.json         everything split_layers.py learned, all posters
      shots.json          the edit spec - written by Claude, step 4
      index.html          GENERATED by build_composition.py
      renders/            finished MP4s
"""

import json
import os
import sys
import urllib.request

# Claude Code reads script output through a pipe, which Windows encodes in the
# ANSI code page - Hebrew then dies with UnicodeEncodeError on non-Hebrew Windows.
for _stream in (sys.stdout, sys.stderr):
    if hasattr(_stream, "reconfigure"):
        _stream.reconfigure(encoding="utf-8", errors="replace")

SKILL_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEMPLATES = os.path.join(SKILL_DIR, "templates")
MODEL_DIR = os.path.join(os.path.expanduser("~"), ".cache", "poster-motion")

# Canvas presets. 4:5 is what the reference film used and what Instagram and
# WhatsApp show uncropped; 9:16 for Reels/Shorts/Status.
CANVAS = {"4:5": (720, 900), "9:16": (720, 1280), "1:1": (900, 900)}
DEFAULT_ASPECT = "4:5"
FPS = 30

POSTER_EXTS = (".png", ".jpg", ".jpeg", ".webp")
DOWNLOAD_TRIES = 4
DOWNLOAD_TIMEOUT_S = 600


def project_arg():
    """The project folder from argv[1], made absolute; exits with usage if absent."""
    if len(sys.argv) < 2 or sys.argv[1].startswith("-"):
        script = os.path.basename(sys.argv[0])
        sys.exit(f"usage: python {script} <project-folder> [options]")
    path = os.path.abspath(sys.argv[1])
    os.makedirs(path, exist_ok=True)
    return path


def flag(name, default=None):
    """Value of `--name value` in argv, or True for a bare `--name`."""
    key = f"--{name}"
    if key not in sys.argv:
        return default
    i = sys.argv.index(key)
    if i + 1 < len(sys.argv) and not sys.argv[i + 1].startswith("--"):
        return sys.argv[i + 1]
    return True


def read_json(path):
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def write_json(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(data, fh, ensure_ascii=False, indent=2)


def list_posters(project):
    """Poster files in reading order: p1, p2 ... p10 (numeric, not lexical)."""
    folder = os.path.join(project, "posters")
    if not os.path.isdir(folder):
        sys.exit(f"missing {folder} - put the poster images there (p1.png ...)")
    names = [n for n in os.listdir(folder) if n.lower().endswith(POSTER_EXTS)]

    def order(name):
        stem = os.path.splitext(name)[0]
        digits = "".join(ch for ch in stem if ch.isdigit())
        return (int(digits) if digits else 10 ** 6, stem)

    return [os.path.join(folder, n) for n in sorted(names, key=order)]


def poster_id(path):
    return os.path.splitext(os.path.basename(path))[0]


def download(url, dest):
    """Fetch url to dest with retries. HuggingFace's CDN resets connections
    intermittently on some networks - a retry, not a different mirror, fixes it."""
    if os.path.exists(dest) and os.path.getsize(dest) > 0:
        return dest
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    tmp = dest + ".part"
    last = None
    for attempt in range(1, DOWNLOAD_TRIES + 1):
        try:
            with urllib.request.urlopen(url, timeout=DOWNLOAD_TIMEOUT_S) as r, \
                    open(tmp, "wb") as fh:
                while chunk := r.read(1 << 20):
                    fh.write(chunk)
            os.replace(tmp, dest)
            return dest
        except OSError as exc:
            last = exc
            print(f"  download attempt {attempt}/{DOWNLOAD_TRIES} failed: {exc}")
    sys.exit(f"could not download {url}: {last}. Check the network, or fetch it "
             f"by hand into {dest}")
